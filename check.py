# -*- coding: utf-8 -*-
# прогін тексту проти стоп-листа. запуск: python3 check.py < draft.txt
import sys, re

T = sys.stdin.read()
low = T.lower()
bad = []

def find(pat, msg, flags=re.I|re.U):
    for m in re.finditer(pat, T, flags):
        frag = T[max(0,m.start()-40):m.end()+40].replace("\n"," ")
        bad.append(f"{msg}: ...{frag}...")

# підсилювачі
find(r"\bсаме\b", "слово САМЕ")
find(r"\bось\b", "слово ОСЬ")
find(r"\bдійсно\b", "ДІЙСНО")
find(r"\bсправді\b", "СПРАВДІ")
find(r"\bвласне\b", "ВЛАСНЕ")
find(r"\bнасправді\b", "НАСПРАВДІ")
find(r"по суті", "ПО СУТІ")

# протиставлення
find(r"\bне\s+[^,.;]{1,45},\s*а\s+", "протиставлення НЕ X, А Y")
find(r"\bце не\b[^.]{0,40}\.\s*це\b", "протиставлення ЦЕ НЕ X. ЦЕ Y")
find(r"не просто\b[^,.]{0,40},\s*(а|це)\b", "НЕ ПРОСТО X, А Y")
find(r"не тому що\b[^.]{0,60}\bа тому що\b", "НЕ ТОМУ ЩО... А ТОМУ ЩО")

# парні заперечення
find(r"\bбез\s+[^,.;]{1,30}\s+і\s+без\b", "парне БЕЗ X І БЕЗ Y")
find(r"\bне\s+[^,.;]{1,30}\s+і\s+не\b", "парне НЕ X І НЕ Y")
find(r"\bні\s+[^,.;]{1,25}\s+ні\b", "парне НІ X НІ Y")
find(r"\bжодн[а-яі]*\b[^.]{0,40}\bі\s+жодн", "парне ЖОДНОГО І ЖОДНОГО")

# анонсування
for p in ["і ще одна річ","а тепер про","тепер найважливіше","скажу тобі одразу",
          "і от що цікаво","і скажу тобі чому","а тепер найцікавіше","тепер про",
          "тепер по ","скажу коротко","скажу тобі прямо","і я в цьому впевнена",
          "перше що прийшло","перше, що прийшло","я бачу що","і головне",
          "але найважливіше","і це говорить про тебе"]:
    find(re.escape(p), f"вставка/анонс: {p}")

# шаблонна сцена з телефоном
for p in ["тримав телефон","тримала телефон","відкривав чат","відкривав ваш чат",
          "набрав і стер","екраном донизу","не спав довго","довго сидів сам",
          "заходив у ваш чат"]:
    find(re.escape(p), f"шаблон з телефоном: {p}")

# узагальнення про абстрактних людей
for p in ["чоловік, якому байдуже","байдужий не мовчить","чоловіки завжди",
          "чоловік його типу","чоловік його складу","він не з тих","вона не з тих",
          "людина, яка","для чоловіка, який"]:
    find(re.escape(p), f"узагальнення: {p}")

# строки
find(r"\b\d{1,2}[-\s]?(го|е|ї)?\s*(січня|лютого|березня|квітня|травня|червня|липня|серпня|вересня|жовтня|листопада|грудня)", "конкретна ДАТА")
find(r"\b(понеділок|вівторок|середу|середа|четвер|п.?ятниц|субот|неділ)", "ДЕНЬ ТИЖНЯ (можна лише якщо клієнт назвав сам)")
find(r"між\s+(перш|друг|трет|четверт|п.?ят|шост|сьом|восьм|дев.?ят|десят|одинадцят|дванадцят)[а-яі]*\s+і", "ГОДИНА")

# фінали
find(r"давай візьмемо годину", "шаблонний фінал")
if T.count("🙏") > 1: bad.append("🙏 більше одного разу")
if len(re.findall(r"[\U0001F300-\U0001FAFF☀-➿]", T)) > 1:
    bad.append("більше одного емодзі")

# форматування
find(r"[—–]", "тире")
find(r"^\s*[-*•]\s", "список", re.M)
find(r"«[^»]{1,60}»|\"[^\"]{1,60}\"", "лапки для драматизму")

# рвані речення
for para in T.split("\n"):
    s = [x.strip() for x in re.split(r"(?<=[.!?])\s+", para) if x.strip()]
    run = 0
    for x in s:
        run = run + 1 if len(x) < 45 else 0
        if run >= 3:
            bad.append(f"три короткі речення підряд: {para[:80]}...")
            break

# афоризм у кінці абзацу
for para in [p for p in T.split("\n") if p.strip()]:
    s = [x.strip() for x in re.split(r"(?<=[.!?])\s+", para) if x.strip()]
    if s and re.match(r"^(це|і це|такі люди|людина|чоловік|жінка)\b", s[-1], re.I) and len(s[-1]) < 120:
        bad.append(f"схоже на афоризм-висновок у кінці: {s[-1]}")

print("ЧИСТО" if not bad else "\n".join(dict.fromkeys(bad)))
