# -*- coding: utf-8 -*-
# прогін тексту проти стоп-листа. запуск: python3 check.py < draft.txt
import sys, re

BLOCK = "--блок" in sys.argv or "--block" in sys.argv
T = sys.stdin.read()
low = T.lower()
bad = []

def find(pat, msg, flags=re.I|re.U):
    for m in re.finditer(pat, T, flags):
        frag = T[max(0,m.start()-40):m.end()+40].replace("\n"," ")
        bad.append(f"{msg}: ...{frag}...")

# підсилювачі
find(r"(?<!те )(?<!й те )\bсаме\b", "слово САМЕ")
find(r"\bось\b", "слово ОСЬ")
find(r"(^|[\s,.])і\s+от\b|\bа\s+от\b|\bот\s+(це|тут|тоді|чому|звідки)\b", "слово ОТ (та сама конструкція, що й ОСЬ)")
find(r"\bдійсно\b", "ДІЙСНО")
find(r"\bсправді\b", "СПРАВДІ")
find(r"\bвласне\b", "ВЛАСНЕ")
find(r"\bнасправді\b", "НАСПРАВДІ")
find(r"по суті", "ПО СУТІ")

# протиставлення
find(r"\bне\s+[^,.;]{1,45},\s*а\s+", "протиставлення НЕ X, А Y")
find(r"\bце не\b[^.]{0,40}\.\s*це\b", "протиставлення ЦЕ НЕ X. ЦЕ Y")
find(r",\s*а\s+не\s+", "протиставлення X, А НЕ Y")
find(r"\bце не\b[^.]{0,60}[,.]\s*це\b", "протиставлення ЦЕ НЕ X, ЦЕ Y")
find(r"\bтримає (його|її) не\b", "протиставлення ТРИМАЄ НЕ X")
find(r"не просто\b[^,.]{0,40},\s*(а|це)\b", "НЕ ПРОСТО X, А Y")
find(r"не тому що\b[^.]{0,60}\bа тому що\b", "НЕ ТОМУ ЩО... А ТОМУ ЩО")

# парні заперечення
find(r"\bбез\s+[^,.;]{1,30}\s+і\s+без\b", "парне БЕЗ X І БЕЗ Y")
find(r"\bне\s+[^,.;]{1,30}\s+і\s+не\b", "парне НЕ X І НЕ Y")
find(r"\bні\s+[^.;]{1,25}\s+ні\b", "парне НІ X НІ Y")
find(r"\bжодн[а-яі]*\b[^.]{0,40}\bі\s+жодн", "парне ЖОДНОГО І ЖОДНОГО")

# анонсування
find(r"(^|[.!?]\s+)тепер (про|по)\b", "анонс на початку речення: тепер про/по")
find(r"\b(скажу|кажу)\s+(тобі\s+)?прямо\b", "вставка: скажу/кажу прямо")
for p in ["і ще одна річ","а тепер про","тепер найважливіше","скажу тобі одразу",
          "і от що цікаво","і скажу тобі чому","а тепер найцікавіше","скажу коротко","і я в цьому впевнена",
          "є ще одна річ","є ще дещо","ще одна деталь","ще один момент","є ще один момент",
          "перше що прийшло","перше, що прийшло","я бачу що","і головне",
          "але найважливіше","і це говорить про тебе"]:
    find(re.escape(p), f"вставка/анонс: {p}")

# шаблонна сцена з телефоном
for p in ["тримав телефон","тримала телефон","відкривав чат","відкривав ваш чат",
          "набрав і стер","екраном донизу","не спав довго","довго сидів сам",
          "заходив у ваш чат"]:
    find(re.escape(p), f"шаблон з телефоном: {p}")

# узагальнення про абстрактних людей
for p in ["коли чоловік", "чоловік починає", "чоловіки завжди", "жінки завжди",
          "жінка на його місці", "чоловік, якому байдуже","байдужий не мовчить","чоловіки завжди",
          "чоловік його типу","чоловік його складу","він не з тих","вона не з тих",
          "людина, яка","для чоловіка, який"]:
    find(re.escape(p), f"узагальнення: {p}")

# строки
find(r"\b\d{1,2}[-\s]?(го|е|ї)?\s*(січня|лютого|березня|квітня|травня|червня|липня|серпня|вересня|жовтня|листопада|грудня)", "конкретна ДАТА")
find(r"\b(понеділ(ок|ка|ку)|вівторок|вівторка|серед(а|у|и)|четвер(?![а-яі])|четверга|четвергу|п.?ятниц|субот|неділ(я|і|ю|ею))\b", "ДЕНЬ ТИЖНЯ (можна лише якщо клієнт назвав сам)")
find(r"між\s+(перш|друг|трет|четверт|п.?ят|шост|сьом|восьм|дев.?ят|десят|одинадцят|дванадцят)[а-яі]*\s+і", "ГОДИНА")

# фінали
find(r"давай візьмемо годину", "шаблонний фінал")
if T.count("🙏") > 1: bad.append("🙏 більше одного разу")
if len(re.findall(r"[\U0001F300-\U0001FAFF☀-➿]", T)) > 1:
    bad.append("більше одного емодзі")

# форматування
find(r"[—–]", "тире")
find(r"^\s*[-*•]\s", "список", re.M)
find(r"«[^»]{1,60}»|\"[^\"]{1,60}\"", "лапки для драматизму")

# рвані речення
for para in T.split("\n"):
    s = [x.strip() for x in re.split(r"(?<=[.!?])\s+", para) if x.strip()]
    run = 0
    for x in s:
        run = run + 1 if len(x) < 45 else 0
        if run >= 3:
            bad.append(f"три короткі речення підряд: {para[:80]}...")
            break

# афоризм у кінці абзацу
for para in [p for p in T.split("\n") if p.strip()]:
    s = [x.strip() for x in re.split(r"(?<=[.!?])\s+", para) if x.strip()]
    if s and re.match(r"^(це|і це|такі люди|людина|чоловік|жінка)\b", s[-1], re.I) and len(s[-1]) < 120:
        bad.append(f"схоже на афоризм-висновок у кінці: {s[-1]}")

# ---- структурні маркери ШІ ----

# інтенсифікатори-милиці
if len(re.findall(r"\bдуже\b", low)) > 1: bad.append("ДУЖЕ більше одного разу на текст")
find(r"\bще (більше|сильніше|гірше|дужче|ближче)\b", "підсилювач ЩЕ БІЛЬШЕ/СИЛЬНІШЕ")

# пара однорідних через І: коротке і звичайне, мʼяким і винуватим
ADV = {"раніше","пізніше","більше","менше","вперше","рідше","частіше","довше","швидше",
       "найбільше","найдовше","найчастіше","ближче","далі","одразу","знову"}
END = ("ий","им","ім","ою","ої","ний","ним","шим","шою","е","ше")
for m in re.finditer(r"\b(\w{5,})\s+і\s+(більш\s+|менш\s+)?(\w{5,})\b", T, re.I|re.U):
    a, b = m.group(1).lower(), m.group(3).lower()
    if a in ADV or b in ADV: continue
    if a.endswith(END) and b.endswith(END) and a[-2:] == b[-2:]:
        frag = T[max(0,m.start()-40):m.end()+40].replace("\n"," ")
        bad.append(f"пара однорідних через І, лишити одне: ...{frag}...")

# книжні звороти, яких не пишуть у чаті
for p in ["ловить себе на","ловлю себе на","прийти до тями","прийшов до тями","прийшла до тями",
          "поклала слухавку","поклав слухавку","з кожним тижнем","з кожним днем",
          "навіть у такі дні","багато тепла","тягнеться до тебе","тягне до тебе",
          "в глибині душі","де б він не був","де б вона не була"]:
    find(re.escape(p), f"книжна фраза: {p}")

# купа хеджів в одному реченні
for sent in re.split(r"(?<=[.!?\n])\s+", T):
    h = len(re.findall(r"\b(десь|раптом|чомусь|трохи|скоріше за все|мабуть|наче|ніби|якось)\b", sent, re.I))
    if h >= 2: bad.append(f"два і більше хеджі в одному реченні: {sent[:70]}")

find(r",\s*(наче|ніби|немов)\s+[^.\n]{0,45}([.\n]|$)", "порівняння-прикраса в кінці речення")
find(r"\bраніше\b[^.\n]{0,140}\bтепер\b", "каркас РАНІШЕ... ТЕПЕР")
find(r"\b(хоче|хотів|збирається|готовий|хочеться)\b[^.\n]{0,70}\b(тільки|але|проте)\b[^.\n]{0,45}\b(не знає|не може|не готов|поки)\b",
     "прогноз із вбудованим виправданням (сам себе скасовує)")

# час доби у прогнозі
_FUT = r"(напише|подзвонить|зателефонує|набере|приїде|з.?явиться|вийде на зв|відповість|захоче|прийде)"
_TOD = r"(зранку|вранці|увечері|ввечері|вночі|надвечір|посеред дня|вдень|опівдні)"
for sent in re.split(r"(?<=[.!?\n])\s+", T):
    if re.search(_FUT, sent, re.I) and re.search(_TOD, sent, re.I):
        bad.append(f"час доби у прогнозі, клієнт звірить: {sent[:80]}")

# самі дієслова стану, жодної дії
_STATE = r"\b(відчува|почуваєть|боїть|боїшся|хоче|думає|згадує|розуміє|переживає|тягнеть|сумує|мріє|шкодує|цінує)"
for para in [x for x in T.split("\n") if x.strip()]:
    if len(re.findall(_STATE, para, re.I)) >= 3:
        bad.append(f"три і більше дієслів стану, у повідомленні нічого не відбувається: {para[:70]}...")

# шаблонний фінал
for p in ["приходь, коли будеш готова","я тебе чекаю","чекаю на тебе","коли будеш готова","я тебе жду"]:
    find(re.escape(p), f"шаблонний фінал, переформулювати: {p}")

# однаковий ритм у блоці повідомлень. вмикається прапорцем --блок,
# коли на вхід іде серія окремих повідомлень, по одному на рядок
_msgs = [x.strip() for x in T.split("\n") if len(x.strip()) > 40]
if BLOCK and len(_msgs) >= 3:
    _L = [len(x) for x in _msgs]
    _avg = sum(_L) / len(_L)
    if (max(_L) - min(_L)) / _avg < 0.6:
        bad.append(f"однакова довжина повідомлень підряд ({min(_L)}-{max(_L)}), читається як машина")
    if min(_L) > 120:
        bad.append(f"жодного короткого повідомлення в серії, найкоротше {min(_L)} символів")
    _first = [x.split()[0].lower() for x in _msgs]
    for w in set(_first):
        if _first.count(w) >= max(3, len(_msgs)//2):
            bad.append(f"однаковий початок повідомлень: {w} ({_first.count(w)} разів)")

print("ЧИСТО" if not bad else "\n".join(dict.fromkeys(bad)))
